import json
from datetime import datetime
from typing import Dict, Any

class ReportGenerator:
    """
    Generates detailed performance analysis reports
    """
    
    def __init__(self):
        pass
    
    def generate_report(self, analysis_results: Dict[str, Any]) -> str:
        """
        Generate a comprehensive markdown report
        """
        report = []
        
        # Header
        report.append("# DPU Performance Studio Analysis Report")
        report.append(f"\n**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        report.append("\n---\n")
        
        # Executive Summary
        report.append("## Executive Summary")
        report.append(self._generate_executive_summary(analysis_results))
        
        # Performance Comparison
        report.append("\n## Performance Comparison")
        report.append(self._generate_performance_comparison(analysis_results))
        
        # Stage-by-Stage Analysis
        report.append("\n## Stage-by-Stage Analysis")
        report.append(self._generate_stage_analysis(analysis_results))
        
        # Bottleneck Analysis
        report.append("\n## Bottleneck Analysis")
        report.append(self._generate_bottleneck_analysis(analysis_results))
        
        # Operation Placement Decisions
        report.append("\n## Operation Placement Decisions")
        report.append(self._generate_placement_decisions(analysis_results))
        
        # Recommendations
        report.append("\n## Recommendations")
        report.append(self._generate_recommendations(analysis_results))
        
        # Data Source Notice
        report.append("\n## Data Source Notice")
        report.append(self._generate_data_source_notice())
        
        # Footer
        report.append("\n---")
        report.append("\n*Report generated by DPU Performance Studio*")
        report.append("*Software-first approach with CPU measurement and DPU simulation*")
        
        return "\n".join(report)
    
    def _generate_executive_summary(self, results: Dict) -> str:
        """
        Generate executive summary section
        """
        cpu_baseline = results["cpu_baseline"]
        optimized = results["optimized_results"]
        comparison = results["comparison"]
        
        summary = f"""
### Key Metrics

- **CPU Baseline Latency:** {cpu_baseline['total_latency_ms']}ms
- **Optimized Latency:** {optimized['total_latency_ms']}ms
- **Performance Improvement:** {comparison['summary']['speedup']}x speedup
- **Latency Reduction:** {comparison['summary']['latency_reduction_ms']}ms
- **Assessment:** {comparison['assessment']['verdict']}

### Summary

{comparison['assessment']['message']}

The analysis identified the primary bottleneck and provided intelligent recommendations
for operation placement across CPU, DPU, and custom kernel paths.
"""
        return summary
    
    def _generate_performance_comparison(self, results: Dict) -> str:
        """
        Generate performance comparison section
        """
        cpu = results["cpu_baseline"]
        dpu = results["dpu_simulation"]
        optimized = results["optimized_results"]
        comparison = results["comparison"]
        
        table = f"""
| Metric | CPU Baseline | DPU Simulated | Optimized |
|--------|-------------|---------------|-----------|
| Total Latency | {cpu['total_latency_ms']}ms | {dpu['total_latency_ms']}ms | {optimized['total_latency_ms']}ms |
| Throughput | {cpu['throughput_samples_per_sec']:.2f} samples/s | {dpu['throughput_samples_per_sec']:.2f} samples/s | {optimized['throughput_samples_per_sec']:.2f} samples/s |
| CPU Utilization | {cpu['avg_cpu_utilization_percent']}% | 30% (sim) | {comparison['resource_comparison']['cpu_utilization']['optimized']}% |
| Transfer Time | 0ms | {dpu['total_transfer_time_ms']}ms | {optimized['total_transfer_time_ms']}ms |
| Sync Time | 0ms | {dpu['total_sync_time_ms']}ms | {optimized['total_sync_time_ms']}ms |

### Resource Utilization Changes

- **CPU Utilization Change:** {comparison['resource_comparison']['cpu_utilization']['change']}% ({comparison['resource_comparison']['cpu_utilization']['change_percentage']}%)
- **DPU Utilization:** {comparison['resource_comparison']['dpu_utilization']['optimized']}% (from 0%)
"""
        return table
    
    def _generate_stage_analysis(self, results: Dict) -> str:
        """
        Generate stage-by-stage analysis section
        """
        cpu = results["cpu_baseline"]
        optimized = results["optimized_results"]
        
        stages = []
        for stage_name in cpu["stages"].keys():
            cpu_stage = cpu["stages"][stage_name]
            opt_stage = optimized["stages"][stage_name]
            speedup = cpu_stage["latency_ms"] / opt_stage["latency_ms"]
            improvement = ((cpu_stage["latency_ms"] - opt_stage["latency_ms"]) / cpu_stage["latency_ms"] * 100)
            
            stages.append(f"""
### {stage_name.replace('_', ' ').upper()}

- **Execution Location:** {opt_stage['execution_location']}
- **CPU Latency:** {cpu_stage['latency_ms']}ms
- **Optimized Latency:** {opt_stage['latency_ms']}ms
- **Speedup:** {speedup:.2f}x
- **Improvement:** {improvement:.1f}%
""")
        
        return "\n".join(stages)
    
    def _generate_bottleneck_analysis(self, results: Dict) -> str:
        """
        Generate bottleneck analysis section
        """
        bottlenecks = results["bottlenecks"]
        
        section = f"""
### Primary Bottleneck

**Type:** {bottlenecks['primary_bottleneck']['type']}
**Description:** {bottlenecks['primary_bottleneck']['description']}
**Impact:** {bottlenecks['primary_bottleneck']['impact']}

### Potential Improvement

- **Current Speedup with Full DPU:** {bottlenecks['potential_improvement']['current_speedup_with_full_dpu']}x
- **Estimated Optimized Latency:** {bottlenecks['potential_improvement']['estimated_optimized_latency_ms']}ms
- **Estimated Speedup:** {bottlenecks['potential_improvement']['estimated_speedup']}x
- **Improvement Percentage:** {bottlenecks['potential_improvement']['improvement_percentage']}%

### Detected Bottlenecks

"""
        
        for bottleneck in bottlenecks["cpu_bottlenecks"]:
            section += f"- **{bottleneck['type']}** in {bottleneck['stage']}: {bottleneck['description']} (Severity: {bottleneck['severity']})\n"
        
        for bottleneck in bottlenecks["stage_bottlenecks"]:
            section += f"- **{bottleneck['type']}** in {bottleneck['stage']}: {bottleneck['net_benefit_ms']:.2f}ms benefit possible\n"
        
        return section
    
    def _generate_placement_decisions(self, results: Dict) -> str:
        """
        Generate operation placement decisions section
        """
        placement = results["placement_decision"]
        summary = placement["summary"]
        
        section = f"""
### Placement Summary

- **Total Stages:** {summary['total_stages']}
- **CPU Stages:** {summary['cpu_stages']} ({summary['distribution']['cpu_percent']}%)
- **DPU Stages:** {summary['dpu_stages']} ({summary['distribution']['dpu_percent']}%)
- **Custom Kernel Stages:** {summary['custom_kernel_stages']} ({summary['distribution']['custom_percent']}%)

### Expected Performance

- **Estimated Total Latency:** {summary['estimated_total_latency_ms']}ms
- **Estimated Speedup:** {summary['estimated_speedup']}x
- **Improvement:** {summary['improvement_percentage']}%

### Stage-by-Stage Decisions

"""
        
        for stage_name, decision in placement["placements"].items():
            section += f"""
#### {stage_name.replace('_', ' ').upper()}

- **Location:** {decision['location']}
- **Reason:** {decision['reason']}
- **CPU Latency:** {decision['estimated_cpu_latency_ms']}ms
- **Optimized Latency:** {decision.get('estimated_dpu_latency_ms', decision.get('estimated_custom_latency_ms', decision['estimated_cpu_latency_ms']))}ms
- **Confidence:** {decision['confidence'] * 100:.0f}%
"""
        
        return section
    
    def _generate_recommendations(self, results: Dict) -> str:
        """
        Generate recommendations section
        """
        comparison = results["comparison"]
        bottlenecks = results["bottlenecks"]
        
        section = "### Bottleneck Recommendations\n\n"
        
        for rec in bottlenecks["recommendations"]:
            section += f"- {rec}\n"
        
        section += "\n### Final Assessment Recommendations\n\n"
        
        for rec in comparison["recommendations"]:
            section += f"- {rec}\n"
        
        return section
    
    def _generate_data_source_notice(self) -> str:
        """
        Generate data source notice section
        """
        return """
> **Important Notice About Data Sources**
>
> - **CPU Results:** These are actual measured values from CPU baseline execution. High confidence.
> - **DPU Results:** These are simulated/emulated values. Real DPU measurements require hardware. Medium confidence.
> - **Custom Kernel:** These are future real-DPU implementation estimates. Performance is estimated. Lower confidence.
>
> This platform uses a software-first approach with CPU measurement and DPU simulation/emulation.
> Real DPU integration is planned for future releases.
"""
    
    def generate_json_report(self, analysis_results: Dict[str, Any]) -> str:
        """
        Generate JSON report for programmatic access
        """
        report = {
            "metadata": {
                "generated_at": datetime.now().isoformat(),
                "tool": "DPU Performance Studio",
                "version": "1.0.0"
            },
            "summary": {
                "cpu_baseline_latency_ms": analysis_results["cpu_baseline"]["total_latency_ms"],
                "optimized_latency_ms": analysis_results["optimized_results"]["total_latency_ms"],
                "speedup": analysis_results["comparison"]["summary"]["speedup"],
                "improvement_percentage": analysis_results["comparison"]["summary"]["improvement_percentage"],
                "assessment": analysis_results["comparison"]["assessment"]["verdict"]
            },
            "detailed_results": analysis_results
        }
        
        return json.dumps(report, indent=2)
